export function detectLang() {
  const saved = localStorage.getItem("dp-lang");
  if (saved && STRINGS[saved]) return saved;
  const nav = (navigator.language || "zh").toLowerCase();
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

export function applyLang(lang) {
  const pack = STRINGS[lang] || STRINGS.zh;
  document.documentElement.lang = LANG_HTML[lang] || "zh-CN";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });

  const title =
    lang === "zh"
      ? "飞舞粒子 · Dancing Particle"
      : lang === "ja"
        ? "Dancing Particle · 飛舞粒子"
        : "Dancing Particle · 飞舞粒子";
  document.title = title;

  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", META_DESC[lang] || META_DESC.zh);

  document.querySelectorAll(".lang button").forEach((btn) => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });

  localStorage.setItem("dp-lang", lang);
}
